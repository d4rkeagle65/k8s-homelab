"""Writes scripts/ha_iot_setup.yaml from NetBox, and with --pr opens a pull request for it.

ha_iot_setup.py reads the file to know which integration adds each kind of IoT device. NetBox
owns what goes in it, from the active IoT devices (netbox_seed.py's, described "Kea
reservation device") and two kinds of NetBox data:

- Tags on the devices, both defined by netbox_seed.py: `ha-setup` on each device Home
  Assistant adds by its address, `ha-attended` on those of them whose setup needs someone at
  the device (a prompt or PIN on a TV). A device type is in the file once a device of it
  carries `ha-setup`, and every active IoT device of that type has to carry it, and agree on
  `ha-attended`, so `?tag=ha-setup` and `?tag=ha-attended` in NetBox's device list are
  exactly what the file holds. An IoT device without `ha-setup` is a cloud integration's,
  set up by hand, and ha_iot_setup.py only puts it in a room.
- Config contexts holding a `home_assistant` key, each assigned to the device types it
  covers, with the settings ha_iot_setup.py needs for those types (none of them a secret):
      home_assistant:
        handler: androidtv                 # the integration's domain
        fields: {device_class: firetv, port: 5555}   # optional: the first step's answers
        login: {username: TPLINK_USERNAME, password: TPLINK_PASSWORD}  # optional: env names
        derived_mac: {interface: eth0, add: -3}      # optional: a MAC Home Assistant reports
  A type tagged `ha-setup` needs a `handler`. `derived_mac` applies to every IoT device of
  its type, tagged or not (an ESP32 reports its base MAC, not its Ethernet one). A type in
  two such contexts, or a key not listed above, refuses the file.

It stops, writing and opening nothing, when NetBox doesn't answer, no device carries
`ha-setup` (an empty file would turn every setup off), or the tags or contexts disagree as
above; each problem is named. The output is sorted, so a run with nothing changed writes the
same bytes and opens nothing.

--pr, when the file differs from main's: points the branch netbox/ha-iot-setup at main,
commits the file there and opens a pull request, or updates the one already open, as
netbox_guests.py does (its file_pull_request). Credentials are never arguments:
NETBOX_TOKEN (read-only) and, for --pr, GITHUB_TOKEN (Contents and Pull requests on this
repository), each from the environment; NetBox's address is NETBOX_API.
"""
from __future__ import annotations

import argparse
import json
import re
import os
import sys
import urllib.error
from pathlib import Path

from ruamel.yaml import YAML

# netbox_seed.py and netbox_guests.py sit beside this script, so Python finds them when it runs it.
import netbox_guests
from netbox_seed import IOT_DEVICE_MARK, NetBox, read_secret

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "scripts/ha_iot_setup.yaml"
BRANCH = "netbox/ha-iot-setup"
SETUP_TAG, ATTENDED_TAG = "ha-setup", "ha-attended"
CONTEXT_KEY = "home_assistant"
SETTINGS = {"handler", "fields", "login", "derived_mac"}
HEADER = """\
# Which Home Assistant integration adds each kind of IoT device by its address
# (scripts/ha_iot_setup.py). Generated by scripts/ha_iot_generate.py from NetBox: edit NetBox
# (the devices' ha-setup and ha-attended tags, and the home_assistant config contexts on their
# device types; that script's docstring says how), not this file, which its next pull request
# replaces.
"""


class Refused(Exception):
    """NetBox's answer can't be turned into the file; nothing is written."""


def type_settings(contexts: list[dict]) -> dict[str, dict]:
    """{device type slug: its home_assistant settings} from the active config contexts."""
    by_type: dict[str, tuple[str, dict]] = {}
    problems = []
    for c in contexts:
        settings = (c.get("data") or {}).get(CONTEXT_KEY)
        if settings is None or not c.get("is_active", True):
            continue
        if not isinstance(settings, dict):
            problems.append(f"config context {c['name']}: {CONTEXT_KEY} isn't a mapping")
            continue
        extra = sorted(set(settings) - SETTINGS)
        if extra:
            problems.append(f"config context {c['name']}: {CONTEXT_KEY} has keys it doesn't take: {', '.join(extra)}")
        problems += [f"config context {c['name']}: {p}" for p in setting_problems(settings)]
        types = [t["slug"] for t in c.get("device_types") or []]
        if not types:
            problems.append(f"config context {c['name']}: assigned to no device type")
        for t in types:
            if t in by_type:
                problems.append(f"device type {t}: in two config contexts ({by_type[t][0]}, {c['name']})")
            else:
                by_type[t] = (c["name"], settings)
    if problems:
        raise Refused("; ".join(problems))
    return {t: s for t, (_, s) in by_type.items()}


def setting_problems(s: dict) -> list[str]:
    out = []
    if "handler" in s and not (isinstance(s["handler"], str) and s["handler"].strip()):
        out.append("handler isn't a name")
    if "fields" in s and not isinstance(s["fields"], dict):
        out.append("fields isn't a mapping")
    login = s.get("login")
    if login is not None and not (isinstance(login, dict) and set(login) <= {"username", "password"}
                                  and all(isinstance(v, str) and v for v in login.values())):
        out.append("login names username and password environment variables, nothing else")
    dm = s.get("derived_mac")
    if dm is not None and not (isinstance(dm, dict) and set(dm) == {"interface", "add"}
                               and isinstance(dm["interface"], str) and isinstance(dm["add"], int)):
        out.append("derived_mac is {interface: <name>, add: <whole number>}")
    return out


def build(devices: list[dict], contexts: list[dict]) -> dict:
    """The file's content: integrations, one per device type tagged ha-setup, and derived_macs."""
    settings = type_settings(contexts)
    iot = [d for d in devices if (d.get("description") or "") == IOT_DEVICE_MARK]
    by_type: dict[str, list[dict]] = {}
    for d in iot:
        by_type.setdefault(d["device_type"]["slug"], []).append(d)
    problems, integrations = [], []
    for d in iot:
        tags = {t["slug"] for t in d.get("tags") or []}
        if ATTENDED_TAG in tags and SETUP_TAG not in tags:
            problems.append(f"{d['name']}: tagged {ATTENDED_TAG} without {SETUP_TAG}")
    for type_, members in sorted(by_type.items()):
        tagged = [d["name"] for d in members if SETUP_TAG in {t["slug"] for t in d.get("tags") or []}]
        if not tagged:
            continue
        untagged = sorted(d["name"] for d in members if d["name"] not in tagged)
        if untagged:
            problems.append(f"device type {type_}: {SETUP_TAG} on {', '.join(sorted(tagged))} but not on "
                            f"{', '.join(untagged)} (a type is set up for all its devices or none)")
        attended = {d["name"] for d in members if ATTENDED_TAG in {t["slug"] for t in d.get("tags") or []}}
        if attended and attended != set(tagged):
            problems.append(f"device type {type_}: {ATTENDED_TAG} on {', '.join(sorted(attended))} but not on "
                            f"{', '.join(sorted(set(tagged) - attended))}")
        s = settings.get(type_) or {}
        if not s.get("handler"):
            problems.append(f"device type {type_}: tagged {SETUP_TAG} but no config context gives it a "
                            f"{CONTEXT_KEY}.handler")
            continue
        entry = {"type": type_, "handler": s["handler"]}
        if attended:
            entry["attended"] = True
        if s.get("fields"):
            entry["fields"] = s["fields"]
        if s.get("login"):
            entry["login"] = s["login"]
        integrations.append(entry)
    if problems:
        raise Refused("; ".join(problems))
    if not integrations:
        raise Refused(f"no active IoT device is tagged {SETUP_TAG}: a file with no integration would turn "
                      "every setup off")
    derived = [{"type": t, "interface": s["derived_mac"]["interface"], "add": s["derived_mac"]["add"]}
               for t, s in sorted(settings.items()) if s.get("derived_mac")]
    return {"integrations": integrations, "derived_macs": derived}


PLAIN = re.compile(r"[A-Za-z_][A-Za-z0-9_.-]*")
YAML_WORDS = {"true", "false", "yes", "no", "on", "off", "null", "y", "n", "~"}


def flow(value) -> str:
    """One value in YAML's flow style, as the hand-written file has it: a name unquoted
    (`password: TPLINK_PASSWORD`, which reads as the variable's name it is, never as a quoted
    literal), anything else as JSON, which YAML reads too."""
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k}: {flow(v)}" for k, v in value.items()) + "}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str) and PLAIN.fullmatch(value) and value.lower() not in YAML_WORDS:
        return value
    return json.dumps(value)


def render(content: dict) -> str:
    """The file: the header, then each entry as one flow mapping on its line, sorted."""
    lines = [HEADER, "integrations:"]
    lines += [f"- {flow(e)}" for e in content["integrations"]]
    lines.append("")
    lines.append("derived_macs:" + ("" if content["derived_macs"] else " []"))
    lines += [f"- {flow(e)}" for e in content["derived_macs"]]
    return "\n".join(lines) + "\n"


def entry_key(e: dict) -> str:
    return f"type {e['type']}" if "type" in e else f"manufacturer {e.get('manufacturer')}"


def changes(old_text: str, new_text: str) -> list[str]:
    """What a pull request's description lists: each integration and derived MAC added,
    removed or changed, by its type (a hand-written entry by manufacturer, by that)."""
    load = YAML(typ="safe", pure=True).load
    old, new = (load(old_text) or {}) if old_text else {}, load(new_text) or {}
    lines = []
    for section in ("integrations", "derived_macs"):
        a = {entry_key(e): e for e in old.get(section) or []}
        b = {entry_key(e): e for e in new.get(section) or []}
        for k in sorted(set(a) | set(b)):
            if k not in a:
                lines.append(f"- {section} {k}: added")
            elif k not in b:
                lines.append(f"- {section} {k}: removed")
            elif a[k] != b[k]:
                diff = ", ".join(f"{f} {a[k].get(f)} -> {b[k].get(f)}" for f in sorted(set(a[k]) | set(b[k]))
                                 if a[k].get(f) != b[k].get(f))
                lines.append(f"- {section} {k}: {diff}")
    return lines


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--output", default=str(ROOT / OUTPUT), help=f"where to write (default {OUTPUT})")
    ap.add_argument("--pr", action="store_true", help="open or update the pull request when main's file differs")
    args, extras = ap.parse_known_args()
    sys.stdout.reconfigure(line_buffering=True)
    if extras:
        raise SystemExit(netbox_guests.unexpected(extras))
    url = os.environ.get("NETBOX_API", "")
    if not url:
        raise SystemExit("FAIL: set NETBOX_API (https://netbox.<domain>)")
    if args.pr and not os.environ.get("GITHUB_TOKEN"):
        raise SystemExit("FAIL: --pr needs GITHUB_TOKEN; nothing was written")
    try:
        nb = NetBox(url, read_secret(".netbox-token", "NETBOX_TOKEN"), apply=False)
        devices = nb.all("dcim/devices", description=IOT_DEVICE_MARK, status="active")
        contexts = nb.all("extras/config-contexts")
        content = build(devices, contexts)
        text = render(content)
        Path(args.output).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.output}: {len(content['integrations'])} integrations "
              f"({sum(bool(e.get('attended')) for e in content['integrations'])} attended), "
              f"{len(content['derived_macs'])} derived MACs, from {len(devices)} active IoT devices")
        if args.pr:
            netbox_guests.file_pull_request(
                OUTPUT, BRANCH, text, os.environ["GITHUB_TOKEN"],
                message="netbox: Home Assistant's IoT setups from NetBox", title="NetBox: Home Assistant IoT setups",
                intro=("Which integration adds each kind of IoT device, generated from NetBox's `ha-setup` and "
                       "`ha-attended` tags and its `home_assistant` config contexts by `scripts/ha_iot_generate.py`. "
                       "Merging changes nothing in Home Assistant until `scripts/ha_iot_setup.py` next runs."),
                summarize=changes)
    except (Refused, netbox_guests.Refused, urllib.error.URLError, OSError) as e:
        raise SystemExit(f"FAIL: {getattr(e, 'reason', None) or e}; no pull request was opened")


if __name__ == "__main__":
    main()
