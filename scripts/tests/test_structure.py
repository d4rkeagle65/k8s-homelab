def test_local_substitution_manifests_are_well_formed(repo_root, load_yaml):
    from k8s_backup.varsub import LOCAL_CONFIGMAP_PATH, LOCAL_SECRET_PATH, load_substitutions

    substitutions = load_substitutions(repo_root)
    configmap_path = repo_root.joinpath(*LOCAL_CONFIGMAP_PATH)
    secret_path = repo_root.joinpath(*LOCAL_SECRET_PATH)

    has_configmap_vars = any(s.get("sensitivity", "configmap") != "secret" for s in substitutions)
    has_secret_vars = any(s.get("sensitivity") == "secret" for s in substitutions)

    if has_configmap_vars:
        doc = load_yaml(configmap_path)
        assert doc["kind"] == "ConfigMap"
        assert doc["metadata"]["name"] == "cluster-substitutions"
        assert doc["metadata"]["namespace"] == "flux-system"
    if has_secret_vars:
        doc = load_yaml(secret_path)
        assert doc["kind"] == "Secret"
        assert doc["metadata"]["name"] == "cluster-substitutions-secret"
        assert doc["metadata"]["namespace"] == "flux-system"


def test_cluster_resources_kustomization_matches_substitutions(repo_root, load_yaml):
    ks_path = repo_root / "kubernetes" / "flux" / "config" / "cluster-resources.yaml"
    if not ks_path.exists():
        pytest.skip("no kubernetes/cluster yet; run `capture` and `generate` first")

    from k8s_backup.varsub import load_substitutions

    substitutions = load_substitutions(repo_root)
    has_configmap_vars = any(s.get("sensitivity", "configmap") != "secret" for s in substitutions)
    has_secret_vars = any(s.get("sensitivity") == "secret" for s in substitutions)

    doc = load_yaml(ks_path)
    assert doc["apiVersion"] == "kustomize.toolkit.fluxcd.io/v1"
    assert doc["kind"] == "Kustomization"
    assert doc["metadata"]["name"] == "cluster-resources"
    assert doc["spec"]["path"] == "./kubernetes/cluster"
    assert doc["spec"]["prune"] is True

    substitute_from = doc["spec"].get("postBuild", {}).get("substituteFrom", [])
    kinds_present = {entry["kind"] for entry in substitute_from}
    assert ("ConfigMap" in kinds_present) == has_configmap_vars
    assert ("Secret" in kinds_present) == has_secret_vars
    for entry in substitute_from:
        assert entry.get("optional") is True, "substituteFrom entries must be optional so Flux doesn't hard-fail before the ConfigMap/Secret exists on the cluster"


