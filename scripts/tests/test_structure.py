"""Structural checks: the generated tree matches the layout the generator
promises (task spec's "Target output structure"), and every generated file
is internally consistent with the others (e.g. a namespace's kustomization
actually lists every release dir that exists on disk).

These are regression tests for the generator, not just the output: a bug
that makes capture.py and generate.py disagree about a path shows up here
even if kubeconform would happily validate each file in isolation.
"""

