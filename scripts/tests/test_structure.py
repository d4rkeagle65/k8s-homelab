_VARIABLE_RE = re.compile(r"(?<!\$)\$\{([A-Za-z_][A-Za-z0-9_]*)\}")

# The azure-keyvault-bootstrap Secret's variables, applied by hand (old-queues/QUEUE-azure-keyvault.md):
# the store that builds cluster-secrets can't take its own address from cluster-secrets. Only
# the azure-keyvault folder may use them, and its Kustomization substitutes from that Secret.
_BOOTSTRAP_SECRET_NAME = "azure-keyvault-bootstrap"
_BOOTSTRAP_VARIABLES = {"AZURE_KEYVAULT_URL", "AZURE_TENANT_ID"}
_BOOTSTRAP_FOLDER = "kubernetes/prod/system/external-secrets/azure-keyvault/"

# A Go template's actions ({{ ... }}), and the fields (.NAME) each one reads.
_TEMPLATE_ACTION_RE = re.compile(r"\{\{(.*?)\}\}", re.DOTALL)
_TEMPLATE_FIELD_RE = re.compile(r"(?<![\w.])\.([A-Za-z_][A-Za-z0-9_]*)")


def _template_key_problem(name: str, text: str, fields: set[str]) -> str | None:
    """Why cluster-secrets' template can't build the key `name` from `text`, or None when it
    can. A key named after a field replaces that field's value (template.data is written
    last), which is allowed only to base64 the field's own plain Key Vault value, written
    exactly {{ .NAME | b64enc }} so that a tool reading the live template can tell it by its
    text. Any other key is built from mapped fields only."""
    if name in fields:
        own = f"{{{{ .{name} | b64enc }}}}"
        return None if text == own else f"has a field's name, so it must be exactly {own}"
    sources = {field for action in _TEMPLATE_ACTION_RE.findall(text) for field in _TEMPLATE_FIELD_RE.findall(action)}
    if not sources:
        return "reads no field"
    if sources - fields:
        return f"reads fields that aren't mapped: {sorted(sources - fields)}"
    return None


def test_every_substituted_variable_is_defined(repo_root, load_yaml):
    """Flux fails a Kustomization on an undefined ${VAR} (strict substitution,
    the default since kustomize-controller v1.9), so every one used under
    kubernetes/ must be a key
    of cluster-settings (public, in git) or a variable of the cluster-secrets
    ExternalSecret (private, from Azure Key Vault). The test overlay's own
    variables come from cluster-substitutions-test, and the azure-keyvault
    store's from the bootstrap Secret applied by hand.
    """
    settings = load_yaml(repo_root / "kubernetes/flux/meta/vars/cluster-settings.yaml")["data"]
    test_vars = load_yaml(repo_root / "kubernetes/flux/meta/vars/cluster-substitutions-test.yaml")["data"]
    external = load_yaml(repo_root / "kubernetes/secrets/cluster-secrets.yaml")
    secrets = {d["secretKey"] for d in external["spec"]["data"]}
    assert not set(settings) & secrets, "a variable is defined both in git and in Key Vault"
    # One Key Vault secret per variable, named after it with "_" as "-" (Key Vault allows
    # only letters, digits and "-"), so Dockhand and the cluster read the same names.
    assert external["spec"]["secretStoreRef"]["name"] == "azure-keyvault"
    for d in external["spec"]["data"]:
        assert d["remoteRef"] == {"key": d["secretKey"].replace("_", "-")}, \
            f"{d['secretKey']}: must read the Key Vault secret {d['secretKey'].replace('_', '-')}, nothing else"
    fields = {"A", "B"}
    assert _template_key_problem("A", "{{ .A | b64enc }}", fields) is None
    assert _template_key_problem("C", "x {{ .A }}:{{ .B | b64enc }}", fields) is None
    for other_form in ("{{ .A }}", "{{.A | b64enc}}", "{{ .B | b64enc }}", "{{ .A | b64dec }}", "x{{ .A | b64enc }}"):
        assert _template_key_problem("A", other_form, fields), f"A built as {other_form} passed"
    assert _template_key_problem("C", "{{ .A }} {{ .D | b64enc }}", fields) == "reads fields that aren't mapped: ['D']"
    assert _template_key_problem("C", "constant", fields) == "reads no field"
    # Variables built from those by the target's template, or encoded by it. Without
    # Merge, a template's keys replace every variable's, and all the others vanish.
    template = external["spec"]["target"].get("template") or {}
    built = set(template.get("data") or {})
    if built:
        assert template.get("mergePolicy") == "Merge", "cluster-secrets' template must use mergePolicy: Merge"
        problems = {name: why for name, text in template["data"].items()
                    if (why := _template_key_problem(name, text, secrets))}
        assert not problems, f"cluster-secrets' template: {problems}"
    secrets |= built

    kubernetes = repo_root / "kubernetes"
    local_root = kubernetes / ".local"
    used: dict[str, set[str]] = {}
    for path in kubernetes.rglob("*.yaml"):
        if path.is_relative_to(local_root) or path.parts[-3:-1] == ("flux", "config") and path.name == "gotk-components.yaml":
            continue
        for name in _VARIABLE_RE.findall(path.read_text(encoding="utf-8")):
            used.setdefault(name, set()).add(path.relative_to(repo_root).as_posix())
    defined = set(settings) | secrets | set(test_vars) | _BOOTSTRAP_VARIABLES
    undefined = {name: sorted(paths)[:3] for name, paths in used.items() if name not in defined}
    assert not undefined, f"variables used but defined nowhere: {undefined}"

    assert not _BOOTSTRAP_VARIABLES & (set(settings) | secrets), "a bootstrap variable is also a cluster variable"
    outside = {name: sorted(p for p in paths if not p.startswith(_BOOTSTRAP_FOLDER))
               for name, paths in used.items() if name in _BOOTSTRAP_VARIABLES}
    assert not any(outside.values()), f"bootstrap variables used outside {_BOOTSTRAP_FOLDER}: {outside}"
    if any(name in _BOOTSTRAP_VARIABLES for name in used):
        ks = load_yaml(repo_root / _BOOTSTRAP_FOLDER / "ks.yaml")
        sources = {(s.get("kind"), s.get("name")) for s in ks["spec"].get("postBuild", {}).get("substituteFrom", [])}
        assert ("Secret", _BOOTSTRAP_SECRET_NAME) in sources, f"{_BOOTSTRAP_FOLDER}ks.yaml must substitute from {_BOOTSTRAP_SECRET_NAME}"


_ROUTER_MIDDLEWARES = "traefik.ingress.kubernetes.io/router.middlewares"


def _walk(node):
    """Every dict nested anywhere in a parsed YAML document, the document included."""
    if isinstance(node, dict):
        yield node
        for value in node.values():
            yield from _walk(value)
    elif isinstance(node, list):
        for value in node:
            yield from _walk(value)


def _middleware_ref_problem(ref: str, defined: set[tuple[str, str]]) -> str | None:
    """Why Traefik can't resolve one router.middlewares entry, or None when it can. Under
    safe naming a CRD Middleware is <namespace>_<name>@kubernetescrd."""
    base, _, provider = ref.partition("@")
    if provider != "kubernetescrd" or "$" in ref:
        return None
    namespace, sep, name = base.partition("_")
    if not sep:
        return "not <namespace>_<name>"
    return None if (namespace, name) in defined else "no such Middleware"


def test_traefik_middleware_references_resolve(repo_root):
    """Traefik drops a router whose middleware it can't resolve, and that app then answers
    404 for every request. Each router.middlewares entry must name a Middleware defined in
    git, as <namespace>_<name>@kubernetescrd (Traefik's safe naming here).
    """
    defined_fixture = {("traefik", "redirect-https")}
    assert _middleware_ref_problem("traefik_redirect-https@kubernetescrd", defined_fixture) is None
    assert _middleware_ref_problem("traefik-redirect-https@kubernetescrd", defined_fixture) == "not <namespace>_<name>"
    assert _middleware_ref_problem("traefik_redirect-http@kubernetescrd", defined_fixture) == "no such Middleware"

    tracked = subprocess.run(["git", "ls-files", "-z", "--", "kubernetes/*.yaml"], cwd=repo_root,
                             capture_output=True, check=True).stdout.decode("utf-8").split("\0")
    defined: set[tuple[str, str]] = set()
    refs: list[tuple[str, str]] = []
    for rel in filter(None, tracked):
        text = (repo_root / rel).read_text(encoding="utf-8")
        if "Middleware" not in text and _ROUTER_MIDDLEWARES not in text:
            continue
        parts = Path(rel).parts
        folder_ns = parts[3] if len(parts) > 3 and parts[1] == "prod" else ""
        for doc in _yaml.load_all(text):
            for node in _walk(doc):
                if node.get("kind") == "Middleware" and str(node.get("apiVersion", "")).startswith("traefik."):
                    meta = node.get("metadata") or {}
                    defined.add((meta.get("namespace") or folder_ns, meta.get("name")))
                value = node.get(_ROUTER_MIDDLEWARES)
                if isinstance(value, str):
                    refs += [(rel, r.strip()) for r in value.split(",") if r.strip()]
    assert defined and refs, "found no Middlewares or no references, so nothing was checked"
    problems = sorted({f"{rel}: {ref} ({why})" for rel, ref in refs
                       if (why := _middleware_ref_problem(ref, defined))})
    assert not problems, "router.middlewares entries Traefik can't resolve:\n" + "\n".join(problems)


