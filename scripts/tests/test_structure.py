"""Structural checks: the generated tree matches the layout the generator
promises (task spec's "Target output structure"), and every generated file
is internally consistent with the others (e.g. a namespace's kustomization
actually lists every release dir that exists on disk).

These are regression tests for the generator, not just the output: a bug
that makes capture.py and generate.py disagree about a path shows up here
even if kubeconform would happily validate each file in isolation.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from k8s_backup.ownership import handwritten_protected_paths, is_handwritten, is_promoted

REQUIRED_TOP_FILES = ["README.md", ".gitignore", ".gitattributes", ".sops.yaml"]
REQUIRED_TOP_DIRS = ["docs", "kubernetes", "scripts", ".github"]
REQUIRED_DOCS = ["inventory.md", "secrets-inventory.csv", "sops-planning.md", "redactions.md", "ip-inventory.csv"]
# Gitignored or empty, so a fresh clone doesn't have them until a run creates them.
LOCAL_ONLY_TOP_DIRS = {"docs", ".github"}

GENERATED_HEADER_PREFIX = "# Generated by k8s-backup-repo-gen on "


def _skip_without_local_capture(repo_root: Path, what: str) -> None:
    """docs/ and kubernetes/raw/ are written by capture and gitignored, so a
    fresh clone (e.g. a cloud session) has neither. kubernetes/.local/ is
    capture's other gitignored output, so its absence means capture never
    ran in this checkout.
    """
    if not (repo_root / "kubernetes" / ".local").is_dir():
        pytest.skip(f"{what} isn't tracked in git, so a fresh clone doesn't have it")


def _awaiting_capture(release_dir: Path) -> bool:
    """Just marked .promote, not captured/generated yet: nothing to check
    until the next run (test_promoted_releases_have_been_captured says so).
    """
    return is_promoted(release_dir) and not (release_dir / "ks.yaml").exists()


def _release_dirs(repo_root: Path):
    apps = repo_root / "kubernetes" / "apps"
    if not apps.exists():
        return
    for ns_dir in sorted(p for p in apps.iterdir() if p.is_dir()):
        for release_dir in sorted(p for p in ns_dir.iterdir() if p.is_dir()):
            if not _awaiting_capture(release_dir):
                yield ns_dir.name, release_dir.name, release_dir


def test_promoted_releases_have_been_captured(repo_root):
    apps = repo_root / "kubernetes" / "apps"
    pending = sorted(
        d.relative_to(repo_root).as_posix()
        for d in (apps.glob("*/*") if apps.exists() else [])
        if d.is_dir() and _awaiting_capture(d)
    )
    assert not pending, (
        f"marked .promote but not captured yet: {pending} -- run "
        "`python scripts/backup.py all --output .` before committing"
    )


def _namespace_dirs(repo_root: Path):
    apps = repo_root / "kubernetes" / "apps"
    if not apps.exists():
        return
    for ns_dir in sorted(p for p in apps.iterdir() if p.is_dir()):
        yield ns_dir.name, ns_dir


