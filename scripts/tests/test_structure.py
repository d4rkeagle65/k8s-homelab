RELEASE_REQUIRED_FILES = [
    "release.yaml",
    "ks.yaml",
    "app/kustomization.yaml",
    "app/helmrelease.yaml",
    "app/values.yaml",
    "app/values-all.yaml",
]
# Written by capture; a hand-written release (.handwritten marker) has none.
CAPTURED_RELEASE_FILES = {"release.yaml", "app/values.yaml", "app/values-all.yaml"}
# A promoted release (.promote marker) is plain manifests, not a Helm release.
PROMOTED_RELEASE_FILES = {"ks.yaml", "app/kustomization.yaml"}


@pytest.mark.parametrize("rel_file", RELEASE_REQUIRED_FILES)
def test_every_release_has_required_files(repo_root, rel_file):
    found_any = False
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        found_any = True
        if is_promoted(release_dir):
            present = (release_dir / rel_file).exists()
            assert present == (rel_file in PROMOTED_RELEASE_FILES), (
                f"{ns_name}/{release_name}/{rel_file}: a promoted release has exactly "
                f"{sorted(PROMOTED_RELEASE_FILES)} of these"
            )
            continue
        if is_handwritten(release_dir):
            if rel_file in CAPTURED_RELEASE_FILES:
                assert not (release_dir / rel_file).exists(), (
                    f"{ns_name}/{release_name}/{rel_file}: hand-written releases must not carry "
                    "captured files -- generate would treat the folder as captured"
                )
                continue
            if rel_file == "app/helmrelease.yaml":
                continue  # a hand-written release may be plain manifests
        assert (release_dir / rel_file).is_file(), f"{ns_name}/{release_name}/{rel_file} missing"
    if not found_any:
        pytest.skip("no releases captured")


def test_ks_yaml_matches_its_release(repo_root, load_yaml):
    kustomizations = {release_name for _, release_name, _ in _release_dirs(repo_root)}
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        doc = load_yaml(release_dir / "ks.yaml")
        assert doc["apiVersion"] == "kustomize.toolkit.fluxcd.io/v1"
        assert doc["kind"] == "Kustomization"
        assert doc["metadata"]["name"] == release_name
        assert doc["metadata"]["namespace"] == "flux-system"
        # A hand-written release may leave it out when its objects name their own
        # namespaces (cluster-policy's LimitRanges); one set always moves them all.
        if not (is_handwritten(release_dir) and "targetNamespace" not in doc["spec"]):
            assert doc["spec"]["targetNamespace"] == ns_name
        assert doc["spec"]["path"] == layout.app_path(release_dir, repo_root)
        # A dependency on a Kustomization that doesn't exist never becomes Ready.
        for dep in doc["spec"]["dependsOn"]:
            assert dep["name"] in kustomizations and dep["name"] != release_name, (
                f"{ns_name}/{release_name}/ks.yaml: dependsOn {dep['name']!r} isn't another "
                "Kustomization under kubernetes/prod/"
            )
        assert doc["spec"]["prune"] is True
        # Without it every ${VAR} reaches the cluster as literal text.
        _assert_wires_substitutions(doc)


def test_every_app_and_service_namespace_has_its_limitrange(repo_root, load_yaml):
    """cluster-policy gives each apps and services namespace its container defaults;
    a namespace added without one would run containers with no requests at all."""
    path = repo_root / "kubernetes/prod/system/cluster-policy/cluster-policy/app/limitranges.yaml"
    with open(path, encoding="utf-8") as f:
        covered = {d["metadata"]["namespace"] for d in _yaml.load_all(f) if d and d["kind"] == "LimitRange"}
    wanted = {
        ns_file.parent.name
        for category in ("apps", "services")
        for ns_file in (repo_root / "kubernetes/prod" / category).glob("*/namespace.yaml")
    }
    assert wanted - covered == set(), f"namespaces with no LimitRange in {path.name}: {sorted(wanted - covered)}"
    assert covered - wanted == set(), f"LimitRanges for namespaces not under apps/ or services/: {sorted(covered - wanted)}"


def _managed_by(release_dir: Path) -> str:
    if is_handwritten(release_dir):
        return layout.MANAGED_HAND
    if is_promoted(release_dir):
        return layout.MANAGED_PROMOTE
    return layout.MANAGED_HELM


