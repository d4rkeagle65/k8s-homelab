@pytest.mark.parametrize("rel_file", RELEASE_REQUIRED_FILES)
def test_every_release_has_required_files(repo_root, rel_file):
    found_any = False
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        found_any = True
        assert (release_dir / rel_file).is_file(), f"{ns_name}/{release_name}/{rel_file} missing"
    if not found_any:
        pytest.skip("no releases captured")


def test_ks_yaml_matches_its_release(repo_root, load_yaml):
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        doc = load_yaml(release_dir / "ks.yaml")
        assert doc["apiVersion"] == "kustomize.toolkit.fluxcd.io/v1"
        assert doc["kind"] == "Kustomization"
        assert doc["metadata"]["name"] == release_name
        assert doc["metadata"]["namespace"] == "flux-system"
        assert doc["spec"]["targetNamespace"] == ns_name
        assert doc["spec"]["path"] == f"./kubernetes/apps/{ns_name}/{release_name}/app"
        assert doc["spec"]["dependsOn"] == []
        assert doc["spec"]["prune"] is True


def test_helmrelease_matches_its_release(repo_root, load_yaml):
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        release_meta = load_yaml(release_dir / "release.yaml")
        hr = load_yaml(release_dir / "app" / "helmrelease.yaml")
        assert hr["apiVersion"] == "helm.toolkit.fluxcd.io/v2"
        assert hr["kind"] == "HelmRelease"
        assert hr["metadata"]["name"] == release_name
        assert hr["metadata"]["namespace"] == ns_name
        assert hr["spec"]["chart"]["spec"]["chart"] == release_meta["chart"]
        assert hr["spec"]["chart"]["spec"]["version"] == release_meta["chartVersion"]

        source_ref = hr["spec"]["chart"]["spec"]["sourceRef"]
        chart_source = release_meta.get("chartSource") or {}
        if chart_source.get("resolved"):
            assert source_ref["name"] == chart_source["name"], (
                f"{ns_name}/{release_name}: helmrelease.yaml sourceRef doesn't match "
                "release.yaml's resolved chartSource"
            )
            assert source_ref["kind"] == chart_source["kind"]
        else:
            assert source_ref["name"] == "REPLACE-ME", (
                f"{ns_name}/{release_name}: chartSource is unresolved in release.yaml but "
                "helmrelease.yaml doesn't carry the REPLACE-ME placeholder -- did someone "
                "hand-edit one of these without the other?"
            )


def test_app_kustomization_lists_helmrelease(repo_root, load_yaml):
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        doc = load_yaml(release_dir / "app" / "kustomization.yaml")
        assert "helmrelease.yaml" in doc["resources"], f"{ns_name}/{release_name}"
        assert "values.yaml" not in doc["resources"], (
            f"{ns_name}/{release_name}: values.yaml is a Helm values file, not a manifest -- "
            "it must never appear in a Kustomize resources: list"
        )


GENERATED_YAML_GLOBS = [
    "kubernetes/apps/*/*/ks.yaml",
    "kubernetes/apps/*/*/app/helmrelease.yaml",
    "kubernetes/apps/*/*/app/kustomization.yaml",
    "kubernetes/apps/*/kustomization.yaml",
    "kubernetes/flux/config/cluster.yaml",
    "kubernetes/flux/meta/repositories/*.yaml",
    "kubernetes/cluster/kustomization.yaml",
]


def test_generated_files_carry_the_generated_header(repo_root):
    checked = 0
    for pattern in GENERATED_YAML_GLOBS:
        for path in repo_root.glob(pattern):
            if path.name == "kustomization.yaml" and "repositories" in path.parts:
                continue
            checked += 1
            first_line = path.read_text(encoding="utf-8").splitlines()[0]
            assert first_line.startswith(GENERATED_HEADER_PREFIX), path
    assert checked > 0, "no generated files found -- run `capture` and `generate` first"


UNSAFE_FILENAME_CHARS = set('<>:"/\\|?*')


def test_no_windows_unsafe_filenames(all_files, repo_root):
    for path in all_files:
        if path.name == ".git":
            continue
        bad = UNSAFE_FILENAME_CHARS & set(path.name)
        assert not bad, f"{path.relative_to(repo_root)} contains characters unsafe on Windows: {bad}"
