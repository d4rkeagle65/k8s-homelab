def test_local_only_cluster_resources_absent_from_tracked_tree(repo_root, load_yaml):
    """Anything skipfilter.classify_cluster_locality would route to
    kubernetes/.local/ must not also exist in the git-tracked
    kubernetes/cluster/ tree (that would defeat the point of the split).
    Uses the real classifier rather than reimplementing its rules, so this
    can't silently drift out of sync with skipfilter.py.
    """
    from k8s_backup.skipfilter import classify_cluster_locality

    cluster_dir = repo_root / "kubernetes" / "cluster"
    if not cluster_dir.exists():
        pytest.skip("no kubernetes/cluster yet; run `capture` first")

    offenders = []
    for kind_dir in cluster_dir.iterdir():
        if not kind_dir.is_dir():
            continue
        for f in kind_dir.glob("*.yaml"):
            try:
                doc = load_yaml(f)
            except Exception:
                continue
            if doc and classify_cluster_locality(kind_dir.name, doc):
                offenders.append(f.relative_to(repo_root))
    assert not offenders, f"built-in/dynamic/infra resource(s) leaked into the git-tracked tree: {offenders}"


