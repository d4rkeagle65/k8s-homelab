def test_namespace_kustomization_lists_namespace_and_every_release(repo_root, load_yaml):
    for ns_name, ns_dir in _namespace_dirs(repo_root):
        kustomization = load_yaml(ns_dir / "kustomization.yaml")
        resources = set(kustomization["resources"])
        assert "namespace.yaml" in resources, ns_name
        release_dirs = {p.name for p in ns_dir.iterdir() if p.is_dir() and not _awaiting_capture(p)}
        expected = {f"{r}/ks.yaml" for r in release_dirs}
        assert resources - {"namespace.yaml"} == expected, ns_name


RELEASE_REQUIRED_FILES = [
    "release.yaml",
    "ks.yaml",
    "app/kustomization.yaml",
    "app/helmrelease.yaml",
    "app/values.yaml",
    "app/values-all.yaml",
]
# Written by capture; a hand-written release (.handwritten marker) has none.
CAPTURED_RELEASE_FILES = {"release.yaml", "app/values.yaml", "app/values-all.yaml"}
# A promoted release (.promote marker) is plain manifests, not a Helm release.
PROMOTED_RELEASE_FILES = {"ks.yaml", "app/kustomization.yaml"}


@pytest.mark.parametrize("rel_file", RELEASE_REQUIRED_FILES)
def test_every_release_has_required_files(repo_root, rel_file):
    found_any = False
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        found_any = True
        if is_promoted(release_dir):
            present = (release_dir / rel_file).exists()
            assert present == (rel_file in PROMOTED_RELEASE_FILES), (
                f"{ns_name}/{release_name}/{rel_file}: a promoted release has exactly "
                f"{sorted(PROMOTED_RELEASE_FILES)} of these"
            )
            continue
        if is_handwritten(release_dir):
            if rel_file in CAPTURED_RELEASE_FILES:
                assert not (release_dir / rel_file).exists(), (
                    f"{ns_name}/{release_name}/{rel_file}: hand-written releases must not carry "
                    "captured files -- generate would treat the folder as captured"
                )
                continue
            if rel_file == "app/helmrelease.yaml":
                continue  # a hand-written release may be plain manifests
        assert (release_dir / rel_file).is_file(), f"{ns_name}/{release_name}/{rel_file} missing"
    if not found_any:
        pytest.skip("no releases captured")


def test_ks_yaml_matches_its_release(repo_root, load_yaml):
    kustomizations = {release_name for _, release_name, _ in _release_dirs(repo_root)}
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        doc = load_yaml(release_dir / "ks.yaml")
        assert doc["apiVersion"] == "kustomize.toolkit.fluxcd.io/v1"
        assert doc["kind"] == "Kustomization"
        assert doc["metadata"]["name"] == release_name
        assert doc["metadata"]["namespace"] == "flux-system"
        assert doc["spec"]["targetNamespace"] == ns_name
        assert doc["spec"]["path"] == f"./kubernetes/apps/{ns_name}/{release_name}/app"
        # A dependency on a Kustomization that doesn't exist never becomes Ready.
        for dep in doc["spec"]["dependsOn"]:
            assert dep["name"] in kustomizations and dep["name"] != release_name, (
                f"{ns_name}/{release_name}/ks.yaml: dependsOn {dep['name']!r} isn't another "
                "Kustomization under kubernetes/apps/"
            )
        assert doc["spec"]["prune"] is True


def test_helmrelease_matches_its_release(repo_root, load_yaml):
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        if is_handwritten(release_dir) or is_promoted(release_dir):
            continue  # no release.yaml to match
        release_meta = load_yaml(release_dir / "release.yaml")
        hr = load_yaml(release_dir / "app" / "helmrelease.yaml")
        assert hr["apiVersion"] == "helm.toolkit.fluxcd.io/v2"
        assert hr["kind"] == "HelmRelease"
        assert hr["metadata"]["name"] == release_name
        assert hr["metadata"]["namespace"] == ns_name
        assert hr["spec"]["chart"]["spec"]["chart"] == release_meta["chart"]
        assert hr["spec"]["chart"]["spec"]["version"] == release_meta["chartVersion"]

        source_ref = hr["spec"]["chart"]["spec"]["sourceRef"]
        chart_source = release_meta.get("chartSource") or {}
        if chart_source.get("resolved"):
            assert source_ref["name"] == chart_source["name"], (
                f"{ns_name}/{release_name}: helmrelease.yaml sourceRef doesn't match "
                "release.yaml's resolved chartSource"
            )
            assert source_ref["kind"] == chart_source["kind"]
        else:
            assert source_ref["name"] == "REPLACE-ME", (
                f"{ns_name}/{release_name}: chartSource is unresolved in release.yaml but "
                "helmrelease.yaml doesn't carry the REPLACE-ME placeholder -- did someone "
                "hand-edit one of these without the other?"
            )


def test_handwritten_helmrelease_is_consistent(repo_root, load_yaml):
    repo_dir = repo_root / "kubernetes" / "flux" / "meta" / "repositories"
    repo_names = {
        load_yaml(p)["metadata"]["name"] for p in repo_dir.glob("*.yaml") if p.name != "kustomization.yaml"
    }
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        hr_path = release_dir / "app" / "helmrelease.yaml"
        if not is_handwritten(release_dir) or not hr_path.is_file():
            continue  # plain manifests have no HelmRelease to check
        hr = load_yaml(hr_path)
        assert hr["apiVersion"] == "helm.toolkit.fluxcd.io/v2"
        assert hr["kind"] == "HelmRelease"
        assert hr["metadata"]["name"] == release_name
        source_ref = hr["spec"]["chart"]["spec"]["sourceRef"]
        assert source_ref["name"] in repo_names, (
            f"{ns_name}/{release_name}: sourceRef {source_ref['name']!r} has no file in "
            "kubernetes/flux/meta/repositories/"
        )


def test_app_kustomization_lists_helmrelease(repo_root, load_yaml):
    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        if is_promoted(release_dir):
            continue  # see test_promoted_release_is_consistent
        doc = load_yaml(release_dir / "app" / "kustomization.yaml")
        if is_handwritten(release_dir) and not (release_dir / "app" / "helmrelease.yaml").is_file():
            # Plain manifests: whatever is in app/ must be listed.
            on_disk = sorted(q.name for q in (release_dir / "app").glob("*.yaml") if q.name != "kustomization.yaml")
            assert sorted(doc["resources"]) == on_disk, f"{ns_name}/{release_name}"
            continue
        assert "helmrelease.yaml" in doc["resources"], f"{ns_name}/{release_name}"
        assert "values.yaml" not in doc["resources"], (
            f"{ns_name}/{release_name}: values.yaml is a Helm values file, not a manifest -- "
            "it must never appear in a Kustomize resources: list"
        )


def test_promoted_release_is_consistent(repo_root, load_yaml):
    from k8s_backup.secretscan import REDACTION_PLACEHOLDER

    for ns_name, release_name, release_dir in _release_dirs(repo_root):
        if not is_promoted(release_dir):
            continue
        app_dir = release_dir / "app"
        manifests = {p.name for p in app_dir.glob("*.yaml") if p.name != "kustomization.yaml"}
        assert set(load_yaml(app_dir / "kustomization.yaml")["resources"]) == manifests, (
            f"{ns_name}/{release_name}: app/kustomization.yaml doesn't list exactly the manifests in app/"
        )
        for name in manifests:
            text = (app_dir / name).read_text(encoding="utf-8")
            assert REDACTION_PLACEHOLDER not in text, (
                f"{ns_name}/{release_name}/app/{name}: Flux would apply the redaction placeholder"
            )
            doc = load_yaml(app_dir / name)
            assert doc["metadata"].get("namespace") in (None, ns_name), f"{ns_name}/{release_name}/app/{name}"


GENERATED_YAML_GLOBS = [
    "kubernetes/apps/*/*/ks.yaml",
    "kubernetes/apps/*/*/app/helmrelease.yaml",
    "kubernetes/apps/*/*/app/kustomization.yaml",
    "kubernetes/apps/*/kustomization.yaml",
    "kubernetes/flux/config/cluster.yaml",
    "kubernetes/flux/meta/repositories/*.yaml",
    "kubernetes/cluster/kustomization.yaml",
]


def test_generated_files_carry_the_generated_header(repo_root):
    handwritten = handwritten_protected_paths(repo_root)
    checked = 0
    for pattern in GENERATED_YAML_GLOBS:
        for path in repo_root.glob(pattern):
            if path.name == "kustomization.yaml" and "repositories" in path.parts:
                continue
            if path.relative_to(repo_root).as_posix() in handwritten:
                continue
            checked += 1
            first_line = path.read_text(encoding="utf-8").splitlines()[0]
            assert first_line.startswith(GENERATED_HEADER_PREFIX), path
    assert checked > 0, "no generated files found -- run `capture` and `generate` first"


